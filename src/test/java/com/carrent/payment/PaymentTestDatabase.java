package com.carrent.payment;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.springframework.core.env.StandardEnvironment;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.support.EncodedResource;
import org.springframework.core.io.support.ResourcePropertySource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

/** Owns only schemas generated by this fixture, never the configured application schema. */
final class PaymentTestDatabase implements AutoCloseable {
    static final List<String> LEGACY = List.of("users", "car_categories", "cars", "car_images",
            "bookings", "payments", "notifications");
    static final List<String> CORE = List.of("payment_channels", "payment_obligations", "payment_intents",
            "webhook_inbox", "payment_receipts", "refunds", "payout_attempts");
    static final Path MIGRATION = Path.of("docs/migrations/2026-10-27-01-payment-core.sql");
    final String name = "carrent_p43_" + UUID.randomUUID().toString().replace("-", "");
    final String url;
    final String username;
    final String password;
    final Connection connection;

    PaymentTestDatabase() throws Exception {
        var env = new StandardEnvironment();
        if (Files.exists(Path.of("application-local.properties"))) {
            env.getPropertySources().addLast(new ResourcePropertySource("file:application-local.properties"));
        }
        env.getPropertySources().addLast(new ResourcePropertySource("classpath:application.properties"));
        String configured = env.getRequiredProperty("spring.datasource.url");
        if (!configured.startsWith("jdbc:mysql://")) throw new IllegalStateException("Tests require MySQL");
        int slash = configured.indexOf('/', "jdbc:mysql://".length());
        int query = configured.indexOf('?', slash);
        String server = configured.substring(0, slash + 1);
        String options = query < 0 ? "" : configured.substring(query);
        username = env.getRequiredProperty("spring.datasource.username");
        password = env.getProperty("spring.datasource.password", "");
        url = server + name + options;
        try (var admin = DriverManager.getConnection(server + options, username, password);
             var statement = admin.createStatement()) {
            statement.execute("CREATE DATABASE `" + name + "` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        }
        connection = DriverManager.getConnection(url, username, password);
    }

    void bootstrap(Path path) throws Exception {
        String sql = Files.readString(path, StandardCharsets.UTF_8)
                .replaceAll("(?m)^CREATE DATABASE IF NOT EXISTS carrent[^;]*;\\R?", "")
                .replaceAll("(?m)^USE carrent;\\R?", "");
        if (sql.matches("(?is).*(?:^|\\n)\\s*(?:USE\\s|CREATE\\s+DATABASE|DROP\\s+DATABASE).*")) {
            throw new IllegalArgumentException("Bootstrap may not select or create another schema");
        }
        run(sql, ";");
    }

    void migrate(boolean backupConfirmed) throws Exception {
        execute("SET @carrent_payment_core_backup_confirmed = " + (backupConfirmed ? "1" : "NULL"));
        String sql = Files.readString(MIGRATION, StandardCharsets.UTF_8)
                .replaceAll("(?m)^DELIMITER[^\\r\\n]*", "");
        run(sql, "$$");
    }

    void run(String sql, String separator) {
        ScriptUtils.executeSqlScript(connection,
                new EncodedResource(new ByteArrayResource(sql.getBytes(StandardCharsets.UTF_8)), StandardCharsets.UTF_8),
                false, false, "--", separator, "/*", "*/");
    }

    void execute(String sql) throws SQLException {
        try (var statement = connection.createStatement()) { statement.execute(sql); }
    }

    long number(String sql) throws SQLException {
        try (var statement = connection.createStatement(); var result = statement.executeQuery(sql)) {
            result.next();
            return result.getLong(1);
        }
    }

    Map<String, String> legacySnapshot() throws Exception {
        Map<String, String> result = new LinkedHashMap<>();
        for (String table : LEGACY) {
            var digest = MessageDigest.getInstance("SHA-256");
            try (var statement = connection.createStatement();
                 var rows = statement.executeQuery("SELECT * FROM " + table + " ORDER BY id")) {
                int columns = rows.getMetaData().getColumnCount();
                while (rows.next()) for (int i = 1; i <= columns; i++) {
                    String value = rows.getString(i);
                    byte[] bytes = value == null ? new byte[0] : value.getBytes(StandardCharsets.UTF_8);
                    digest.update((value == null ? "NULL:" : bytes.length + ":").getBytes(StandardCharsets.UTF_8));
                    digest.update(bytes);
                }
            }
            result.put(table, HexFormat.of().formatHex(digest.digest()));
        }
        return result;
    }

    Map<String, String> coreSchema() throws Exception {
        Map<String, String> result = new LinkedHashMap<>();
        for (String table : CORE) {
            try (var statement = connection.createStatement();
                 var rows = statement.executeQuery("SHOW CREATE TABLE " + table)) {
                rows.next();
                result.put(table, rows.getString(2).replaceAll(" AUTO_INCREMENT=\\d+", ""));
            }
        }
        return result;
    }

    @Override
    public void close() throws SQLException {
        try {
            if (!name.matches("carrent_p43_[0-9a-f]{32}") || !connection.getCatalog().equals(name)) {
                throw new IllegalStateException("Refusing to drop a schema not owned by this fixture");
            }
            execute("DROP DATABASE `" + name + "`");
        } finally {
            connection.close();
        }
    }
}
